// synonyms.js — dict คำทับศัพท์ไทย → ชื่อภาษาอังกฤษ (R4)
// ใช้กับ "คำค้นของลูกค้า" เท่านั้น ก่อนค้น (ไม่ใช้กับข้อความสินค้า ซึ่งมีชื่ออังกฤษอยู่แล้ว)
// ทำไมต้องมี: ทดลองแล้วโมเดลรู้จัก "Gundam" แต่ไม่รู้จัก "กันดั้ม" (ค้นแล้วได้ Luffy, Yamato แทน)
// เพราะตอนเทรน โมเดลเห็นคำทับศัพท์แบบไทยน้อยมาก · ตัวแปลภาษาอัตโนมัติก็ถอดชื่อเฉพาะได้ไม่แน่นอน
// จึงใช้ตารางเล็ก ๆ ที่เขียนเอง แม่น 100% (เทคนิคนี้เรียกว่า synonym mapping / query expansion)
// เจอคำที่ลูกค้าค้นแล้วไม่เจอ → เพิ่มในตารางนี้ได้เลย

// [คำไทยหลายแบบที่คนพิมพ์, ชื่อภาษาอังกฤษ]
const SYNONYMS = [
  [['กันดั้ม', 'กันดัม', 'กันพลา'], 'Gundam'],
  [['โปเกมอน', 'โปเกม่อน'], 'Pokémon'],
  [['ชาริซาร์ด', 'ลิซาร์ดอน'], 'Charizard'],
  [['ปิกาจู', 'พิคาชู'], 'Pikachu'],
  [['วันพีซ', 'วันพีช'], 'One Piece'],
  [['ลูฟี่', 'ลูฟี'], 'Luffy'],
  [['ดราก้อนบอล', 'ดรากอนบอล'], 'Dragon Ball'],
  [['โกคู', 'โงกุน'], 'Goku'],
  [['นารูโตะ', 'นารูโต'], 'Naruto'],
  [['ยูกิโอ', 'ยูกิ'], 'Yu-Gi-Oh'],
  [['ดิจิมอน'], 'Digimon'],
  [['ฟันโกะ', 'ฟังโกะ'], 'Funko'],
  [['มาร์เวล'], 'Marvel'],
  [['ป๊อปมาร์ท', 'ป็อปมาร์ท', 'ป๊อบมาร์ท'], 'Pop Mart'],
  [['ลาบูบู้', 'ลาบูบู'], 'Labubu'],
];

// แตกเป็นคู่ [คำไทย, อังกฤษ] แล้วเรียงคำยาวก่อน
// กัน "ยูกิ" ไปแทนกลางคำ "ยูกิโอ" ก่อน (ได้ "Yu-Gi-Ohโอ" ผิด ๆ)
const PAIRS = SYNONYMS.flatMap(([thaiWords, english]) => thaiWords.map((w) => [w, english])).sort(
  (a, b) => b[0].length - a[0].length
);

// "ฟิกเกอร์กันดั้ม" → "ฟิกเกอร์ Gundam"
// ภาษาไทยไม่มีเว้นวรรคระหว่างคำ จึงหาแบบ "มีคำนี้อยู่ตรงไหนก็ได้" แล้วแทนด้วยชื่ออังกฤษที่มีเว้นวรรครอบ
function expandQuery(q) {
  let text = q;
  for (const [thai, english] of PAIRS) {
    text = text.split(thai).join(` ${english} `); // split + join = แทนทุกตำแหน่งที่เจอ
  }
  return text.replace(/\s+/g, ' ').trim(); // เว้นวรรคซ้อน → เหลือช่องเดียว · ตัดหัวท้าย
}

module.exports = { expandQuery, SYNONYMS };